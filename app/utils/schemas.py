"""Schema-contracted Pydantic models (Schema-Contracted Prompts pattern)."""
from __future__ import annotations
from typing import List, Optional, Literal
from pydantic import BaseModel, Field


# ---------- Ingest layer ----------
class DocumentChunk(BaseModel):
    """A single chunk produced by the ingest pipeline."""
    chunk_id: str
    doc_id: str
    source: str  # file name
    page: Optional[int] = None
    modality: Literal["text", "table", "image_caption", "ocr"]
    lang: str = "en"            # 'en' | 'vi' | 'mixed'
    text: str
    meta: dict = Field(default_factory=dict)


# ---------- Co-Scientist state ----------
class Hypothesis(BaseModel):
    """A scientific / analytical hypothesis generated by the Generation Agent."""
    hyp_id: str
    title: str
    body: str
    citations: List[str] = Field(default_factory=list)   # chunk_ids
    novelty: float = 0.0
    feasibility: float = 0.0
    score: float = 0.0  # Elo


class ReflectionReport(BaseModel):
    hyp_id: str
    safety_ok: bool = True
    novelty: float = 0.0          # 0..1
    correctness: float = 0.0      # 0..1
    feasibility: float = 0.0     # 0..1
    assumptions: List[str] = Field(default_factory=list)
    failure_modes: List[str] = Field(default_factory=list)
    notes: str = ""


class RankedHypothesis(BaseModel):
    hyp_id: str
    title: str
    elo: float = 1200.0
    rationale: str = ""


class EvolutionResult(BaseModel):
    parent_ids: List[str]
    new_hypothesis: Hypothesis
    operation: Literal["combination", "grounding", "simplification", "out_of_box"]


class MetaReview(BaseModel):
    final_hypothesis: Hypothesis
    report_markdown: str
    recurring_failure_modes: List[str] = Field(default_factory=list)
